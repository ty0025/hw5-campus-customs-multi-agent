"""Reset the Homework 5 working copy and generate the Problem 2 report.

Run from hw5 with: python study_database.py
Only Python's standard library is required; no AI calls are made.
"""

from __future__ import annotations

import hashlib
import shutil
import sqlite3
from contextlib import closing
from datetime import date
from pathlib import Path


ROOT = Path(__file__).resolve().parent
ORIGINAL = ROOT / "data" / "campus_customs.db"
WORKING = ROOT / "data" / "campus_customs_new.db"
REPORT = ROOT / "output" / "harness.md"

RELEVANCE = {
    "cash_accounts": "Accounting checks available cash before proposing an approved payout, while Boss uses the balance to prioritize obligations.",
    "desk": "Boss, Inventory, Accounting, Facilities, and Customer Service use date_today as the shared business date for overdue checks and customer updates.",
    "inventory": "Inventory matches each requested SKU and size to on-hand quantity and location, while Customer Service uses confirmed availability in drafts.",
    "invoices": "Accounting checks unpaid bills and prepares approved payments, while Inventory checks whether a vendor's unpaid invoices block shipments.",
    "leases": "Facilities checks the space, landlord, rent, and due date, while Accounting uses those facts to prepare a payment for human approval.",
    "payments": "Accounting records approved cash outflows and their authorizers, while Boss checks which obligations have been paid.",
    "pricing": "Accounting calculates margins from unit cost and list price, while Boss evaluates discounts and Customer Service drafts the resulting offer.",
    "tickets": "Boss routes each request to Inventory, Accounting, or Facilities as needed, while Customer Service uses its requester, subject, and notes to draft replies.",
    "vendors": "Inventory reads supplier specialties and lead times, while Accounting checks related invoices and Customer Service uses confirmed timing in drafts.",
}


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def quote_identifier(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def money(value: float) -> str:
    return f"${value:,.2f}"


def due_status(value: str, today: date) -> str:
    days = (date.fromisoformat(value) - today).days
    if days < 0:
        return f"overdue by {-days} days"
    if days == 0:
        return "due today"
    return f"due in {days} days"


def build_report(conn: sqlite3.Connection, source_hash: str) -> tuple[str, int, int]:
    tables = [row["name"] for row in conn.execute(
        "SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name"
    )]
    lines = [
        "# Campus Customs Database Harness", "",
        "Generated by `python study_database.py` from the Homework 5 project root; "
        "the script first copies `data/campus_customs.db` to `data/campus_customs_new.db` "
        "and then inspects the working copy through a read-only sqlite3 connection.", "",
        "## Schema inventory", "",
        "Every table is discovered from `sqlite_master`, and the exact field names "
        "and declared SQLite types below are fetched dynamically with `PRAGMA table_info`.", "",
    ]
    foreign_keys = []
    column_count = 0
    for table in tables:
        quoted = quote_identifier(table)
        columns = conn.execute(f"PRAGMA table_info({quoted})").fetchall()
        count = conn.execute(f"SELECT COUNT(*) FROM {quoted}").fetchone()[0]
        column_count += len(columns)
        lines.extend([f"### `{table}` ({count} {'row' if count == 1 else 'rows'})", ""])
        lines.extend(f"- `{column['name']}`: `{column['type']}`" for column in columns)
        relevance = RELEVANCE.get(table, "Boss and the specialist agents can inspect this table for additional operational context.")
        lines.extend(["", f"**Agent relevance:** {relevance}", ""])
        foreign_keys.extend(
            f"- `{table}.{fk['from']}` references `{fk['table']}.{fk['to']}`."
            for fk in conn.execute(f"PRAGMA foreign_key_list({quoted})")
        )

    today = date.fromisoformat(conn.execute("SELECT date_today FROM desk").fetchone()[0])
    tickets = conn.execute("SELECT * FROM tickets WHERE status = ? ORDER BY id", ("open",)).fetchall()
    if len(tickets) != 3:
        raise ValueError(f"Expected 3 open tickets after reset; found {len(tickets)}.")
    lines.extend([
        "## Open-ticket findings", "",
        f"`desk.date_today` is `{today}`; all overdue calculations below use this shop date, "
        f"and the database contains {len(tickets)} open tickets.", "",
        "### Table linkages", "",
        "Declared foreign keys from `PRAGMA foreign_key_list`:", "",
        *foreign_keys, "",
        "Other operational links:", "",
        "- `(tickets.sku, tickets.size)` matches `(inventory.sku, inventory.size)`, "
        "and `tickets.sku` matches `pricing.sku`; these matches are not declared foreign keys.",
        "- `desk.date_today` supplies the date context for invoices, leases, and ticket handling.",
        "- `payments.account` can match `cash_accounts.name`, and `payments.kind` plus "
        "`payments.ref_id` can identify the paid obligation; these application-level links "
        "are not declared foreign keys and the initial payment ledger is empty.",
        "- No table maps SKUs directly to vendors, so a vendor inferred from product category "
        "and `vendors.specialty` is a candidate rather than a confirmed SKU supplier.", "",
    ])

    for ticket in tickets:
        lines.extend([
            f"### Ticket {ticket['id']}: {ticket['subject']}", "",
            f"- Intake: `{ticket['type']}` from {ticket['requester']}; status `{ticket['status']}`; "
            f"created `{ticket['created_at']}`.",
            f"- Recorded notes: {ticket['notes'] or '(none)'}",
        ])
        if ticket["sku"]:
            stock = conn.execute("SELECT * FROM inventory WHERE sku = ? AND size = ?",
                                 (ticket["sku"], ticket["size"])).fetchone()
            pricing = conn.execute("SELECT * FROM pricing WHERE sku = ?", (ticket["sku"],)).fetchone()
            if stock:
                shortfall = max(0, ticket["qty"] - stock["qty"])
                lines.append(f"- Stock link: `{ticket['sku']}` size `{ticket['size']}` is {stock['name']}; "
                             f"{stock['qty']} on hand at {stock['location']} for a requested {ticket['qty']}, "
                             f"leaving a shortfall of {shortfall}.")
            if pricing:
                margin = pricing["list_price"] - pricing["unit_cost"]
                rate = margin / pricing["list_price"] * 100
                lines.append(f"- Pricing link: unit cost {money(pricing['unit_cost'])}, "
                             f"list price {money(pricing['list_price'])}, and list-price unit gross profit "
                             f"{money(margin)} ({rate:.2f}% gross margin).")
        if ticket["invoice_id"] is not None:
            invoice = conn.execute(
                "SELECT i.*, v.name AS vendor_name, v.specialty, v.lead_days "
                "FROM invoices i JOIN vendors v ON v.id = i.vendor_id WHERE i.id = ?",
                (ticket["invoice_id"],),
            ).fetchone()
            lines.append(f"- Invoice/vendor link: `invoice_id={invoice['id']}` resolves to "
                         f"{invoice['vendor_name']} through `invoices.vendor_id`; amount "
                         f"{money(invoice['amount'])}, status `{invoice['status']}`, due `{invoice['due_date']}` "
                         f"({due_status(invoice['due_date'], today)}), description \"{invoice['description']}\".")
            lines.append(f"- Vendor timing: specialty `{invoice['specialty']}`, recorded lead time "
                         f"{invoice['lead_days']} days; the open unpaid invoice blocks new shipments, "
                         "so that lead time is not an unconditional delivery promise.")
        if ticket["lease_id"] is not None:
            lease = conn.execute("SELECT * FROM leases WHERE id = ?", (ticket["lease_id"],)).fetchone()
            lines.append(f"- Lease link: `lease_id={lease['id']}` resolves to {lease['space_name']}, "
                         f"landlord {lease['landlord']}, monthly rent {money(lease['monthly_rent'])}, "
                         f"next due `{lease['next_due']}` ({due_status(lease['next_due'], today)}).")
        if ticket["type"] == "price_override":
            lines.append("- Discount detail: the request asks for a bulk discount without an exact "
                         "discount or target price, so a discounted margin remains undetermined.")
            candidates = conn.execute("SELECT * FROM vendors WHERE specialty = ?", ("apparel reprint",)).fetchall()
            for vendor in candidates:
                blockers = conn.execute("SELECT id, amount FROM invoices WHERE vendor_id = ? AND status = ?",
                                        (vendor["id"], "open")).fetchall()
                lines.append(f"- Candidate vendor: {vendor['name']} has specialty `{vendor['specialty']}` "
                             f"and a {vendor['lead_days']}-day lead time, making it a category-based "
                             "candidate for the hoodies; ticket 103 has no invoice reference or direct vendor mapping.")
                if blockers:
                    details = ", ".join(f"{row['id']} ({money(row['amount'])})" for row in blockers)
                    lines.append(f"- Vendor restriction: open unpaid invoice {details} blocks this "
                                 "candidate's new shipments, including any hoodie restock.")
        lines.append("")

    accounts = conn.execute("SELECT * FROM cash_accounts ORDER BY name").fetchall()
    payment_count = conn.execute("SELECT COUNT(*) FROM payments").fetchone()[0]
    lines.extend(["### Cash and operating constraints", ""])
    for account in accounts:
        lines.append(f"- `{account['name']}` balance: {money(account['balance'])} as of `{account['date']}`.")
    lines.extend([
        f"- The payment ledger contains {payment_count} rows; this inspection makes no payments or ticket changes.",
        "- Any future payment requires human approval, sufficient cash, and updates to the relevant "
        "records; cash only goes out and balances must not become negative.",
        "- Customer messages and vendor requests stay as board drafts; no email or real vendor call is made.",
        "- Reset the working database from the original before every full ticket run.", "",
        "## Inspection verification", "",
        f"- Discovered {len(tables)} tables, {column_count} fields, and {len(tickets)} open tickets.",
        "- `PRAGMA integrity_check`: `ok`; `PRAGMA foreign_key_check`: no violations.",
        "- Original SHA-256 before and after inspection matches the working copy SHA-256:",
        f"  `{source_hash}`", "",
    ])
    return "\n".join(lines), len(tables), column_count


def main() -> None:
    if not ORIGINAL.is_file():
        raise FileNotFoundError(f"Original database is missing: {ORIGINAL}")
    if WORKING.is_symlink() or (WORKING.exists() and ORIGINAL.samefile(WORKING)):
        raise ValueError("Working database must be a separate regular file from the original.")
    source_hash = digest(ORIGINAL)
    shutil.copy2(ORIGINAL, WORKING)
    if digest(WORKING) != source_hash:
        raise RuntimeError("Working copy does not match the original.")
    with closing(sqlite3.connect(WORKING.resolve().as_uri() + "?mode=ro", uri=True)) as conn:
        conn.row_factory = sqlite3.Row
        if [row[0] for row in conn.execute("PRAGMA integrity_check")] != ["ok"]:
            raise RuntimeError("Database integrity check failed.")
        if conn.execute("PRAGMA foreign_key_check").fetchall():
            raise RuntimeError("Database has foreign key violations.")
        report, table_count, column_count = build_report(conn, source_hash)
    if digest(ORIGINAL) != source_hash or digest(WORKING) != source_hash:
        raise RuntimeError("Database contents changed during inspection.")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    # Q2 owns the database report; keep the Q3 appendix and later sections on reruns.
    if REPORT.exists():
        _, marker, appendix = REPORT.read_text(encoding="utf-8").partition("\n## MCP Tools\n")
        if marker:
            report = report.rstrip() + "\n" + marker + appendix
    REPORT.write_text(report, encoding="utf-8")
    print(f"Generated {REPORT.relative_to(ROOT)}: {table_count} tables, {column_count} fields, 3 open tickets.")
    print("Original unchanged; working copy identical; SQLite integrity and foreign key checks passed.")


if __name__ == "__main__":
    main()
